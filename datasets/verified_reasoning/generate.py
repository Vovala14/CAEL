# ------------------------------------------------------------------ G. ARC-style grid transformations
def rand_grid(rng, h, w, density, colours):
    return [[rng.choice(colours) if rng.random() < density else 0 for _ in range(w)] for _ in range(h)]


def objects4(g):
    h, w = len(g), len(g[0])
    seen, out = set(), []
    for y in range(h):
        for x in range(w):
            if g[y][x] and (y, x) not in seen:
                c, stack, cells = g[y][x], [(y, x)], []
                seen.add((y, x))
                while stack:
                    a, b = stack.pop()
                    cells.append((a, b))
                    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                        na, nb = a + dy, b + dx
                        if 0 <= na < h and 0 <= nb < w and (na, nb) not in seen and g[na][nb] == c:
                            seen.add((na, nb))
                            stack.append((na, nb))
                out.append(cells)
    return out


def t_flip_h(g): return [list(reversed(r)) for r in g]
def t_flip_v(g): return [list(r) for r in reversed(g)]
def t_rot90(g): return [list(r) for r in zip(*g[::-1])]
def t_transpose(g): return [list(r) for r in zip(*g)]


def t_gravity(g):
    h, w = len(g), len(g[0])
    out = [[0] * w for _ in range(h)]
    for x in range(w):
        col = [g[y][x] for y in range(h) if g[y][x]]
        for i, v in enumerate(reversed(col)):
            out[h - 1 - i][x] = v
    return out


def t_scale(k):
    return lambda g: [[v for v in r for _ in range(k)] for r in g for _ in range(k)]


def t_tile(g):
    return [r + r for r in g] + [r + r for r in g]


def t_mirror(g):
    return [r + list(reversed(r)) for r in g]


def t_border(c):
    def f(g):
        h, w = len(g), len(g[0])
        return [[c if y in (0, h - 1) or x in (0, w - 1) else g[y][x] for x in range(w)] for y in range(h)]
    return f


def t_recolour(m):
    return lambda g: [[m.get(v, v) for v in r] for r in g]


def t_crop_largest(g):
    objs = objects4(g)
    if not objs:
        raise ValueError
    sizes = sorted(len(o) for o in objs)
    if len(sizes) > 1 and sizes[-1] == sizes[-2]:
        raise ValueError
    o = max(objs, key=len)
    ys, xs = [p[0] for p in o], [p[1] for p in o]
    cells = set(o)
    return [[g[y][x] if (y, x) in cells else 0 for x in range(min(xs), max(xs) + 1)] for y in range(min(ys), max(ys) + 1)]


def t_stamp(c):
    def f(g):
        h, w = len(g), len(g[0])
        out = [r[:] for r in g]
        for y in range(h):
            for x in range(w):
                if g[y][x]:
                    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                        yy, xx = y + dy, x + dx
                        if 0 <= yy < h and 0 <= xx < w and g[yy][xx] == 0:
                            out[yy][xx] = c
        return out
    return f


def t_span_rows(g):
    out = [r[:] for r in g]
    for y, r in enumerate(g):
        for c in set(r) - {0}:
            xs = [x for x, v in enumerate(r) if v == c]
            if len(xs) >= 2:
                for x in range(xs[0] + 1, xs[-1]):
                    if r[x] == 0:
                        if out[y][x] not in (0, c):
                            raise ValueError
                        out[y][x] = c
    return out


