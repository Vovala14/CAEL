def words(n):
    if n < 20:
        return ONES[n]
    if n < 100:
        return TENS[n // 10] + ('' if n % 10 == 0 else '-' + ONES[n % 10])
    return str(n)


def num(rng, n, p=0.3):
    """A whole number written as digits, or (sometimes) as words."""
    return words(n) if n < 100 and rng.random() < p else str(n)


def money(sym, cents):
    cents = int(cents)
    # Floor division/modulo on a negative value corrupt fractional amounts:
    # -250 cents used to render as -3.50. Format the magnitude, then the sign.
    sign = '-' if cents < 0 else ''
    cents = abs(cents)
    if cents % 100 == 0:
        return f'{sym}{sign}{cents // 100:,}'
    return f'{sym}{sign}{cents // 100:,}.{cents % 100:02d}'


def plural(pair, n):
    return pair[0] if n == 1 else pair[1]


def show_date(d, style=0):
    if style == 1:
        return f'{MONTHS[d.month - 1]} {d.day}, {d.year}'
    return f'{d.day} {MONTHS[d.month - 1]} {d.year}'


def hhmm(m, twelve=False):
    m %= 1440
    h, mi = divmod(m, 60)
    if twelve:
        return f'{(h - 1) % 12 + 1}:{mi:02d} {"am" if h < 12 else "pm"}'
    return f'{h:02d}:{mi:02d}'


def ex(category, task, turns, answer, steps, check, rng_id, extra=None):
    row = dict(category=category, task=task, messages=[dict(role='user', content=t) for t in turns], answer=answer,
               solution=' '.join(steps) if isinstance(steps, list) else steps, verification=check, generator=f'cael-verified-reasoning-{VERSION}')
    if extra:
        row.update(extra)
    return row


