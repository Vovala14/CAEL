"""Build RESULTS.md from results/*.summary.json and results/*.jsonl (every number in the report comes from these files)."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = HERE / 'results'
SYSTEMS = [('cael-0.3.4', 'CAEL 0.3.4 (baseline)'), ('cael-0.3.5-r1', 'CAEL 0.3.5 round 1 (first freeze)'), ('cael-0.3.5', 'CAEL 0.3.5 (round 2, final)'),
           ('qwen2.5-0.5b-instruct', 'Qwen2.5-0.5B-Instruct'), ('smollm2-360m-instruct', 'SmolLM2-360M-Instruct')]
LADDER = [('cael-0.3.4', '0.3.4 baseline'), ('cael-0.3.5-stage1-memory', '+ structured memory & integer records'),
          ('cael-0.3.5-stage2-references', '+ pronouns & indirect references'), ('cael-0.3.5-stage3-updates', '+ updates, history, corrections'),
          ('cael-0.3.5-stage4-conflicts', '+ conflict detection'), ('cael-0.3.5', '+ planning (= 0.3.5)')]
LADDER_R1 = [(t.replace('cael-0.3.5', 'cael-0.3.5-r1'), n) if t != 'cael-0.3.4' else (t, n) for t, n in LADDER]
SPLITS = [('test', 'Held-out test (200 questions)'),
          ('fresh2', 'Blind paraphrase set for round 2 (100 questions, written after the round-2 freeze)'),
          ('fresh', 'Paraphrase set 1 (100 questions): blind for round 1, then used as the round-2 development set'),
          ('dev', 'Development set (120 questions, tuned on in both rounds)')]
CATS = ['memory', 'reference', 'update', 'conflict', 'planning']


def load(tag, split):
    s = R / f'{tag}-{split}.summary.json'
    rows = R / f'{tag}-{split}.jsonl'
    if not s.exists():
        return None, []
    return json.loads(s.read_text(encoding='utf-8')), [json.loads(l) for l in rows.open(encoding='utf-8')]


def fmt(v, unit=''):
    return '—' if v is None else f'{v}{unit}'


def main_table(split):
    out = ['| System | Context acc. | Fact-update acc. | ' + ' | '.join(c.capitalize() for c in CATS) +
           ' | Peak RAM | Median latency | p95 latency | CPU s (total) | Compression |', '|' + '---|' * (9 + len(CATS) - 2 + 2)]
    for tag, name in SYSTEMS:
        s, _ = load(tag, split)
        if not s:
            continue
        cats = ' | '.join(fmt(s['by_category'].get(c, {}).get('accuracy'), '%') for c in CATS)
        out.append(f"| {name} | **{fmt(s['context_accuracy'], '%')}** | **{fmt(s['fact_update_accuracy'], '%')}** | {cats} | "
                   f"{fmt(s['peak_ram_mb'], ' MB')} | {fmt(s['latency_median_s'], ' s')} | {fmt(s['latency_p95_s'], ' s')} | "
                   f"{fmt(s['cpu_seconds_total'])} | {fmt(s['compression_ratio_median'], '×') if s['compression_ratio_median'] else 'n/a'} |")
    return '\n'.join(out)


def ladder(split, steps=LADDER):
    out = ['| Step | Overall | ' + ' | '.join(c.capitalize() for c in CATS) + ' |', '|' + '---|' * (2 + len(CATS))]
    for tag, name in steps:
        s, _ = load(tag, split)
        if s:
            out.append(f"| {name} | {fmt(s['overall'], '%')} | " + ' | '.join(fmt(s['by_category'].get(c, {}).get('accuracy'), '%') for c in CATS) + ' |')
    return '\n'.join(out)


def length_table(split):
    out = ['| System | 5–20 messages | 21–50 messages |', '|---|---|---|']
    for tag, name in SYSTEMS:
        s, _ = load(tag, split)
        if s:
            out.append(f"| {name} | {fmt(s['short_vs_long']['5-20 messages'], '%')} | {fmt(s['short_vs_long']['21-50 messages'], '%')} |")
    return '\n'.join(out)


def failures(tag, split, limit=60):
    _, rows = load(tag, split)
    bad = [r for r in rows if not r['ok']]
    lines = [f'{len(bad)} of {len(rows)} wrong.', '']
    for r in bad[:limit]:
        reply = (r['reply'] or '(no answer)').replace('\n', ' ').replace('|', '/')[:150]
        lines.append(f"- `{r['id']}` — {r['question']} → {reply}")
    return '\n'.join(lines)


def neural_wins(split):
    _, cael = load('cael-0.3.5', split)
    by_id = {r['id']: r for r in cael}
    lines = []
    for tag, name in SYSTEMS[3:]:
        _, rows = load(tag, split)
        wins = [r for r in rows if r['ok'] and not by_id.get(r['id'], {}).get('ok', True)]
        lines.append(f'**{name}** right where CAEL 0.3.5 is wrong: {len(wins)}')
        for r in wins[:15]:
            lines.append(f"- `{r['id']}` — {r['question']} → {name}: {r['reply'][:100]!r} / CAEL: {by_id[r['id']]['reply'][:100]!r}")
        lines.append('')
    return '\n'.join(lines)


if __name__ == '__main__':
    parts = ['# Context & reasoning benchmark — CAEL 0.3.5', '',
             'Generated by `report.py` from `results/`. Reproduce: `python generate.py`, `python paraphrase.py`, then '
             '`bash run_all.sh <python> <cael-0.3.4 checkout> <cael-0.3.5 checkout>` and `python report.py`.', '']
    for split, title in SPLITS:
        parts += [f'## {title}', '', main_table(split), '', '### Before/after each improvement (CAEL 0.3.5, round 2)', '', ladder(split), '']
        if load('cael-0.3.5-r1-stage1-memory', split)[0]:
            parts += ['### Before/after each improvement (round 1)', '', ladder(split, LADDER_R1), '']
        parts += ['### By conversation length', '', length_table(split), '',
                  '### Every CAEL 0.3.5 (round 2) failure', '', failures('cael-0.3.5', split), '']
        if any(load(t, split)[0] for t, _ in SYSTEMS[3:]):
            parts += ['### Where the neural models beat CAEL 0.3.5', '', neural_wins(split), '']
    (HERE / 'RESULTS.md').write_text('\n'.join(parts), encoding='utf-8')
    print('wrote RESULTS.md')
