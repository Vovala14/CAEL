def b_zone(rng):
    c1, c2 = rng.sample(CITIES, 2)
    k = rng.randint(1, 10)
    day = rng.randint(0, 6)
    t = rng.randint(0, 1439)
    ahead = rng.random() < 0.5
    shift = -k if ahead else k   # time in c2 = time in c1 + shift... c1 is k ahead of c2 -> c2 = c1 - k
    total = day * 1440 + t + shift * 60
    d2, t2 = DAYS[(total // 1440) % 7], total % 1440
    rel = 'ahead of' if ahead else 'behind'
    turns = [f'In a story, {c1} clocks run {k} hours {rel} {c2} clocks. An event starts {DAYS[day]} at {hhmm(t)} in {c1}. What day and time is that in {c2}?']
    return ex('dates_times', 'time_zone', turns, f'{d2} {hhmm(t2)}',
              [f'{c2} is {k} hours {"behind" if ahead else "ahead of"} {c1}, so {"subtract" if ahead else "add"} {k} hours: {d2} {hhmm(t2)}.'],
              'modular arithmetic over a week', rng)


