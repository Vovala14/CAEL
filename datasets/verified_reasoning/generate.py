        p1, p2 = rng.randint(150, 900), rng.randint(150, 1400)
        u1, u2 = Fraction(p1, q1), Fraction(p2, q2)
        if u1 != u2 and abs(u1 - u2) / max(u1, u2) > Fraction(3, 100):
            break
