def h_shift_pay(rng):
    sym, _ = rng.choice(CURRENCIES)
    a = rng.randint(6 * 60, 11 * 60) // 5 * 5
    b = a + rng.randint(5 * 60, 11 * 60) // 5 * 5
    brk = rng.choice([15, 20, 30, 45, 60])
    rate = rng.choice(range(1200, 3601, 60))           # per hour, divisible by 60 so per-minute pay is whole cents
    worked = b - a - brk
    pay = rate * worked // 60
    turns = [f'I worked from {hhmm(a)} to {hhmm(b)} with an unpaid {brk}-minute break. I am paid {money(sym, rate)} per hour. How much did I earn?']
    return ex('composite', 'shift_pay', turns, money(sym, pay),
              [f'{hhmm(a)} to {hhmm(b)} is {b - a} minutes; minus {brk} = {worked} minutes.', f'{worked} minutes × {money(sym, rate)} per 60 minutes = {money(sym, pay)}.'],
              'clock arithmetic then exact money arithmetic', rng)


def h_rental(rng):
    sym, _ = rng.choice(CURRENCIES)
    d1 = rand_date(rng, 2015, 2032)
    nights = rng.randint(2, 40)
    d2 = d1 + timedelta(days=nights)
    rate = rng.choice(range(2500, 25001, 250))
    deposit = rng.choice(range(5000, 50001, 2500))
    total = nights * rate
    thing = rng.choice(['cabin', 'flat', 'van', 'boat', 'studio'])
    turns = [f'I rent a {thing} from {show_date(d1)} to {show_date(d2)} at {money(sym, rate)} per night. I already paid a {money(sym, deposit)} deposit that counts towards the total. How much is still due?']
    due = total - deposit
    ans = money(sym, due) if due >= 0 else f'Nothing; {money(sym, -due)} should be refunded'
    return ex('composite', 'rental_due', turns, ans,
              [f'{show_date(d1)} to {show_date(d2)} is {nights} nights.', f'{nights} × {money(sym, rate)} = {money(sym, total)}.',
               f'{money(sym, total)} − {money(sym, deposit)} = {money(sym, due) if due >= 0 else "−" + money(sym, -due)}.'],
              'calendar arithmetic then exact money arithmetic', rng)


def h_flight(rng):
    c1, c2 = rng.sample(CITIES, 2)
    k = rng.randint(1, 9)
    ahead = rng.random() < 0.5
    day = rng.randint(0, 6)
    dep = rng.randint(0, 1439) // 5 * 5
    dur = rng.randint(60, 14 * 60) // 5 * 5
    shift = k if ahead else -k                          # c2 is k hours ahead of / behind c1
    arr = day * 1440 + dep + dur + shift * 60
    turns = [f'In a story, {c2} clocks are {k} hours {"ahead of" if ahead else "behind"} {c1} clocks. A flight leaves {c1} on {DAYS[day]} at {hhmm(dep)} local time and the flight takes {dur // 60} h {dur % 60} min. What day and local time does it land in {c2}?']
    return ex('composite', 'flight_arrival', turns, f'{DAYS[(arr // 1440) % 7]} {hhmm(arr % 1440)}',
              [f'Departure {DAYS[day]} {hhmm(dep)} + {dur // 60} h {dur % 60} min = {DAYS[((day * 1440 + dep + dur) // 1440) % 7]} {hhmm((dep + dur) % 1440)} in {c1} time.',
               f'{"Add" if ahead else "Subtract"} {k} hours for {c2}: {DAYS[(arr // 1440) % 7]} {hhmm(arr % 1440)}.'],
              'clock arithmetic over a week, then a time-zone shift', rng)


def h_budget_days(rng):
    sym, _ = rng.choice(CURRENCIES)
    d1 = rand_date(rng, 2016, 2032)
    d2 = d1 + timedelta(days=rng.randint(7, 90))
    daily = rng.choice(range(500, 6001, 50))
    have = rng.choice(range(10000, 400001, 1000))
    days = (d2 - d1).days + 1
    need = days * daily
    enough = have >= need
    turns = [f'I will travel from {show_date(d1)} to {show_date(d2)}, both days included, and budget {money(sym, daily)} a day. I have saved {money(sym, have)}. Is that enough, and by how much am I over or short?']
    ans = f'Yes, {money(sym, have - need)} to spare' if enough else f'No, {money(sym, need - have)} short'
    return ex('composite', 'trip_budget', turns, ans,
              [f'{show_date(d1)} to {show_date(d2)} inclusive is {days} days.', f'{days} × {money(sym, daily)} = {money(sym, need)}.',
               f'Saved {money(sym, have)}: ' + (f'{money(sym, have - need)} to spare.' if enough else f'{money(sym, need - have)} short.')],
              'inclusive calendar count then exact money arithmetic', rng)


# ------------------------------------------------------------------ wording variety and difficulty
LEADS = ['', '', '', 'Quick question: ', 'Can you help me with this? ', "I'm trying to work something out. ", 'Here is a puzzle. ', 'Help me check this: ']
TAILS = ['', '', '', ' Please show your working.', ' Just give me the answer.', ' Explain briefly.', ' I want to be sure I have this right.']


def vary(row, rng):
    """Wrap the first and last user turns in varied, natural phrasing (the problem itself is unchanged)."""
    if row['category'] == 'arc_grids':
        return row
    msgs = row['messages']
    lead, tail = rng.choice(LEADS), rng.choice(TAILS)
    if lead:
        msgs[0]['content'] = lead + msgs[0]['content']          # the original sentence keeps its capital letter
    if tail:
        msgs[-1]['content'] = msgs[-1]['content'] + tail
    return row


def difficulty(row):
    """A heuristic level: 1 (one step) to 5 (many steps or a large search). Documented in the card."""
    t, cat = row['task'], row['category']
    steps = row['solution'].count('.') + row['solution'].count(';')
    if cat == 'arc_grids':
        g = row['grids']['test']['input']
        cells = len(g) * len(g[0])
        hard = {'crop_largest': 1, 'span_rows': 1, 'stamp_cross': 1, 'gravity_down': 1, 'recolour': 0}.get(t, 0)
        return min(5, 1 + (cells > 20) + (cells > 50) + hard)
    if t == 'lineup':
        n = len(row['messages'][0]['content'].split(':', 1)[1].split('.', 1)[0].split(','))
        return min(5, n - 1)
    if cat == 'composite':
        return 4 if t != 'trip_budget' else 5
    if t in ('comparisons', 'corrected_tally', 'shares_owed', 'discount_then_tax', 'flight_arrival', 'time_zone', 'date_plus_period', 'age_on_date', 'weekday_after'):
        return 3
    if cat in ('unanswerable',) or t.startswith('conditional_affirm') or t.startswith('conditional_deny') or row['answer'] == 'Cannot be determined':
        return 3
    return max(1, min(3, steps - 1))


