def a_change(rng):
    sym, word = rng.choice(CURRENCIES)
    picks = rng.sample(GOODS, rng.randint(2, 3))
    total, parts, items = 0, [], []
    for g in picks:
        k = rng.randint(1, 5)
        price = rng.choice([75, 95, 120, 150, 180, 200, 225, 250, 275, 320, 350, 400, 450, 499, 600])
        total += k * price
        items.append(f'{num(rng, k)} {plural(g, k)} at {money(sym, price)} each')
        parts.append(f'{k} × {money(sym, price)} = {money(sym, k * price)}')
    note = next(v for v in (1000, 2000, 5000, 10000) if v >= total + 1)
    lead = rng.choice(['I bought', 'We ordered', 'At the café I got', 'My basket had'])
    q = rng.choice([f'I pay with a {money(sym, note)} note. How much change should I get?',
                    f'If I hand over {money(sym, note)}, what change do I get back?'])
    turns = [f'{lead} ' + ', '.join(items[:-1]) + f' and {items[-1]}. {q}']
    return ex('arithmetic', 'change', turns, money(sym, note - total),
              parts + [f'Total {money(sym, total)}.', f'Change: {money(sym, note)} − {money(sym, total)} = {money(sym, note - total)}.'],
              'exact integer arithmetic in cents', rng)


