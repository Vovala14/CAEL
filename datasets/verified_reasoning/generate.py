def g_arc(rng):
    name, desc, make, kind = rng.choice(GRID_RULES)
    made = make(rng)
    colours = rng.sample(range(1, 10), rng.randint(1, 3))
    if isinstance(made, tuple) and made[0] == 'c':
        c = made[1]
        fn, desc = t_border(c), desc.format(c=c)
    elif isinstance(made, tuple) and made[0] == 's':
        c = made[1]
        colours = [x for x in colours if x != c] or [((c % 9) + 1)]
        fn, desc = t_stamp(c), desc.format(c=c)
    elif isinstance(made, tuple) and made[0] == 'm':
        src = colours[:]
        dst = rng.sample([x for x in range(1, 10) if x not in src], len(src))
        m = dict(zip(src, dst))
        fn, desc = t_recolour(m), desc.format(m=', '.join(f'{a}→{b}' for a, b in m.items()))
    else:
        fn = made
    pairs = []
    for _ in range(4):
        for _attempt in range(30):
            if kind == 'tiny':
                h, w = rng.randint(2, 4), rng.randint(2, 4)
            elif kind == 'small':
                h, w = rng.randint(2, 6), rng.randint(2, 6)
            else:
                h, w = rng.randint(3, 10), rng.randint(3, 10)
            dens = {'sparse': 0.3, 'very_sparse': 0.12, 'objects': 0.45, 'row_pairs': 0.18}.get(kind, rng.uniform(0.2, 0.6))
            g = rand_grid(rng, h, w, dens, colours)
            if kind == 'row_pairs':
                for r in g:
                    if rng.random() < 0.5:
                        c = rng.choice(colours)
                        a, b = sorted(rng.sample(range(w), 2))
                        r[a] = r[b] = c
            try:
                o = fn(g)
            except ValueError:
                continue
            if o != g and any(v for r in g for v in r):
                pairs.append((g, o))
                break
        else:
            return None
    show = lambda g: '\n'.join(' '.join(map(str, r)) for r in g)
    demo = '\n\n'.join(f'Example {i + 1}\nInput:\n{show(a)}\nOutput:\n{show(b)}' for i, (a, b) in enumerate(pairs[:3]))
    test_in, test_out = pairs[3]
    turns = [f'{demo}\n\nTest input:\n{show(test_in)}\n\nWhat is the test output grid?']
    return ex('arc_grids', name, turns, show(test_out), f'Rule: {desc} Applied to the test input it gives the grid above.',
              'rule applied programmatically to every pair', rng, extra=dict(grids=dict(train=[dict(input=a, output=b) for a, b in pairs[:3]],
                                                                                         test=dict(input=test_in, output=test_out)), rule=name))


