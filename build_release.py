"""Build a portable CAEL source ZIP from exactly the files committed to git."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import zipfile

ROOT = Path(__file__).resolve().parent
VERSION = '0.2.8'


def tracked_files():
    """Exactly the files committed to git: ignored local experiments, caches and weights cannot slip in."""
    import subprocess
    listing = subprocess.run(['git', 'ls-files', '-z'], cwd=ROOT, check=True, capture_output=True).stdout
    return [ROOT / name for name in listing.decode('utf-8').split('\0') if name]


def digest(path):
    value = hashlib.sha256()
    with Path(path).open('rb') as source:
        for block in iter(lambda: source.read(1024 * 1024), b''):
            value.update(block)
    return value.hexdigest()


def public_paths():
    # SHA256SUMS.json is regenerated by this script and appended separately; it cannot list itself.
    paths = sorted(p for p in tracked_files() if p.is_file() and p.name != 'SHA256SUMS.json')
    for path in paths:
        relative = path.relative_to(ROOT)
        if any(part in ('research', 'outputs', '.git', '.venv', 'chat_worker', 'data') for part in relative.parts):
            raise ValueError('Private or local-only path in source archive')
        if path.suffix.lower() in ('.pt', '.safetensors', '.sqlite', '.duckdb', '.cael') or path.name in ('chat_backend.json', 'relay_key.txt', 'ui_token.txt', 'session.key'):
            raise ValueError('Unapproved weight, credential or database in source archive: ' + str(relative))
    return paths


def source_bytes(path):
    """Match Git's declared LF text format without modifying the checkout."""
    raw = path.read_bytes()
    relative = path.relative_to(ROOT)
    binary = relative.parts[0] == 'models' or relative.as_posix() == 'reference/model.json'
    text = path.suffix.lower() in ('.py', '.md', '.json', '.yml', '.yaml', '.txt', '.bat') or path.name in ('.gitignore', '.gitattributes')
    return raw.replace(b'\r\n', b'\n') if text and not binary else raw


def main(out, bundle):
    if out.exists():
        raise FileExistsError(out)
    paths = public_paths()
    sums = {p.relative_to(ROOT).as_posix(): hashlib.sha256(source_bytes(p)).hexdigest() for p in paths}
    if bundle:
        if not bundle.is_file():
            raise FileNotFoundError(bundle)
        config = json.loads((ROOT / 'bundle_config.json').read_text())
        if digest(bundle) != config['sha256']:
            raise ValueError('Bundle differs from release configuration')
        sums[f'models/cael-{VERSION}.cael'] = config['sha256']
    manifest = ROOT / 'SHA256SUMS.json'
    manifest.write_text(json.dumps(sums, indent=2) + '\n', encoding='utf-8')
    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
        for path in paths + [manifest]:
            info = zipfile.ZipInfo(f'CAEL-{VERSION}/' + path.relative_to(ROOT).as_posix(), date_time=(2026, 10, 17, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, source_bytes(path))
        if bundle:
            archive.write(bundle, f'CAEL-{VERSION}/models/cael-{VERSION}.cael', compress_type=zipfile.ZIP_STORED)
    print(json.dumps(dict(archive=str(out), sha256=digest(out), bytes=out.stat().st_size, source_files=len(paths)), indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=ROOT / 'dist' / f'CAEL-{VERSION}.zip')
    parser.add_argument('--bundle', type=Path, default=ROOT / 'dist' / f'cael-{VERSION}.cael')
    parser.add_argument('--source-only', action='store_true')
    args = parser.parse_args()
    main(args.out.resolve(), None if args.source_only else args.bundle.resolve())
