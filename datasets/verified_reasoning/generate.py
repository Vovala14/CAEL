def b_date_plus(rng):
    d0 = rand_date(rng)
    unit = rng.choice(['days', 'weeks', 'months', 'years'])
    n = rng.randint(1, 18) if unit != 'days' else rng.randint(10, 200)
    if unit == 'days':
        d1 = d0 + timedelta(days=n)
    elif unit == 'weeks':
        d1 = d0 + timedelta(weeks=n)
    elif unit == 'months':
        i = d0.year * 12 + d0.month - 1 + n
        y, mo = divmod(i, 12)
        d1 = date(y, mo + 1, min(d0.day, calendar.monthrange(y, mo + 1)[1]))
    else:
        try:
            d1 = d0.replace(year=d0.year + n)
        except ValueError:
            d1 = date(d0.year + n, 2, 28)
    thing = rng.choice(['My membership starts', 'The warranty begins', 'The trial period starts', 'My lease begins'])
    turns = [f'{thing} on {show_date(d0)} and lasts {n} {unit[:-1] if n == 1 else unit}. On what date does it end?']
    note = ' (the month is shorter, so the date is moved to its last day)' if unit in ('months', 'years') and d1.day != d0.day else ''
    return ex('dates_times', 'date_plus_period', turns, show_date(d1), [f'{show_date(d0)} + {n} {unit} = {show_date(d1)}{note}.'],
              'calendar arithmetic with month-end clamping', rng)


