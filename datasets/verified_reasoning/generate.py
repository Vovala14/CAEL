def c_lineup(rng):
    n = rng.randint(3, 6)
    names = rng.sample(NAMES, n)
    order = names[:]
    rng.shuffle(order)
    pos = {nm: i + 1 for i, nm in enumerate(order)}
    scene = rng.choice([('stand in a queue', 'first', 'last', 'in front of', 'behind'), ('sit in a row', 'on the left end', 'on the right end', 'to the left of', 'to the right of'),
                        ('finished a race', 'first', 'last', 'before', 'after')])

    def facts():
        cands = []
        for a, b in itertools.permutations(names, 2):
            if pos[b] - pos[a] == 1:
                cands.append((f'{b} is directly {scene[4]} {a}.' if scene[0] != 'finished a race' else f'{b} finished right after {a}.', lambda p, a=a, b=b: p[b] - p[a] == 1))
            if pos[a] < pos[b]:
                cands.append((f'{a} is {scene[3]} {b}.' if scene[0] != 'finished a race' else f'{a} finished before {b}.', lambda p, a=a, b=b: p[a] < p[b]))
            if abs(pos[a] - pos[b]) > 1 and a < b:
                cands.append((f'{a} is not next to {b}.', lambda p, a=a, b=b: abs(p[a] - p[b]) != 1))
        for a in names:
            if pos[a] == 1:
                cands.append((f'{a} is {scene[1]}.', lambda p, a=a: p[a] == 1))
            if pos[a] == n:
                cands.append((f'{a} is {scene[2]}.', lambda p, a=a: p[a] == len(p)))
            if pos[a] not in (1, n):
                cands.append((f'{a} is not at either end.', lambda p, a=a: p[a] not in (1, len(p))))
        return cands
    pool = facts()
    rng.shuffle(pool)
    chosen = []
    perms = [dict(zip(p, range(1, n + 1))) for p in itertools.permutations(names)]
    target = rng.choice(names) if rng.random() < 0.5 else None
    ask_pos = rng.randint(1, n)
    for text, f in pool:
        chosen.append((text, f))
        perms = [p for p in perms if f(p)]
        if len(perms) == 1:
            break
    if len(perms) != 1:
        return None
    origin = 'from the front' if scene[0].startswith('stand') else 'from the left' if 'row' in scene[0] else 'from first place'
    if target:
        q = f'In which position is {target}, counting {origin}?'
        answer = ORD[pos[target] - 1]
    else:
        q = f'Who is in position {ask_pos}, counting {origin}?'
        answer = order[ask_pos - 1]
    intro = f'{words(n).capitalize()} people {scene[0]}: {", ".join(sorted(names))}.'
    turns = [intro + ' ' + ' '.join(t for t, _ in chosen) + ' ' + q]
    return ex('logic', 'lineup', turns, answer,
              [f'Trying every order of the {n} people, only one satisfies all the statements: ' + ', '.join(order) + '.', f'So the answer is {answer}.'],
              f'exhaustive search over {math.factorial(n)} orders; exactly one survives', rng)


def c_if_then(rng):
    p, c = rng.choice([('it rains', 'the match is cancelled', 'it did not rain', 'the match was not cancelled', 'did it rain', 'is the match cancelled'),
                       ('the alarm goes off', 'the dog barks', 'the alarm did not go off', 'the dog did not bark', 'did the alarm go off', 'did the dog bark'),
                       ('the shop is open', 'the lights are on', 'the shop is closed', 'the lights are off', 'is the shop open', 'are the lights on'),
                       ('you press the button', 'the door opens', 'nobody pressed the button', 'the door stayed shut', 'was the button pressed', 'did the door open'),
                       ('the kettle boils', 'it clicks off', 'the kettle did not boil', 'it did not click off', 'did the kettle boil', 'did it click off')])[:2], None
    rows = {('it rains', 'the match is cancelled'): ('it rained', 'it did not rain', 'the match was cancelled', 'the match was not cancelled', 'Did it rain?', 'Was the match cancelled?'),
            ('the alarm goes off', 'the dog barks'): ('the alarm went off', 'the alarm did not go off', 'the dog barked', 'the dog did not bark', 'Did the alarm go off?', 'Did the dog bark?'),
            ('the shop is open', 'the lights are on'): ('the shop is open', 'the shop is not open', 'the lights are on', 'the lights are not on', 'Is the shop open?', 'Are the lights on?'),
            ('you press the button', 'the door opens'): ('the button was pressed', 'the button was not pressed', 'the door opened', 'the door did not open', 'Was the button pressed?', 'Did the door open?'),
            ('the kettle boils', 'it clicks off'): ('the kettle boiled', 'the kettle did not boil', 'it clicked off', 'it did not click off', 'Did the kettle boil?', 'Did it click off?')}
    P, notP, C, notC, askP, askC = rows[p]
    form = rng.choice(['ponens', 'tollens', 'affirm_consequent', 'deny_antecedent'])
    if form == 'ponens':
        fact, ask, ans, why = P, askC, 'Yes', 'modus ponens: the condition holds, so the result follows'
    elif form == 'tollens':
        fact, ask, ans, why = notC, askP, 'No', 'modus tollens: the result did not happen, so the condition cannot have held'
    elif form == 'affirm_consequent':
        fact, ask, ans, why = C, askP, 'Cannot be determined', 'affirming the consequent is invalid: the result could have another cause'
    else:
        fact, ask, ans, why = notP, askC, 'Cannot be determined', 'denying the antecedent is invalid: the rule says nothing when the condition fails'
    turns = [f'If {p[0]}, {p[1]}. {fact[0].upper() + fact[1:]}. {ask}']
    return ex('logic', f'conditional_{form}', turns, ans, [f'Rule: if {p[0]}, then {p[1]}. Known: {fact}.', why[0].upper() + why[1:] + '.'],
              'propositional logic (truth-table)', rng)


def c_compare(rng):
    adj = rng.choice([('taller', 'shorter', 'tallest', 'shortest'), ('older', 'younger', 'oldest', 'youngest'), ('heavier', 'lighter', 'heaviest', 'lightest'),
                      ('faster', 'slower', 'fastest', 'slowest')])
    n = rng.randint(3, 5)
    order = rng.sample(NAMES, n)            # order[0] has the most
    edges = [(order[i], order[i + 1]) for i in range(n - 1)]
    if n >= 4 and rng.random() < 0.3:
        edges.pop(rng.randint(1, n - 3))    # break the chain in the middle: the extremes may become unknown
    facts = [f'{a} is {adj[0]} than {b}.' if rng.random() < 0.6 else f'{b} is {adj[1]} than {a}.' for a, b in edges]
    rng.shuffle(facts)
    ask_most = rng.random() < 0.5
    beaten = {b for a, b in edges} if ask_most else {a for a, b in edges}
    named = {x for e in edges for x in e}
    cands = sorted(x for x in named if x not in beaten)
    if len(cands) == 1:
        ans = cands[0]
        side = 'losing' if ask_most else 'winning'
        why = f'Only {ans} is never on the {side} side of a comparison, so {ans} is the {adj[2] if ask_most else adj[3]}.'
    else:
        ans = 'Cannot be determined'
        why = f'The comparisons do not connect everyone: {" or ".join(cands)} could each be the {adj[2] if ask_most else adj[3]}.'
    turns = [' '.join(facts) + f' Who is the {adj[2] if ask_most else adj[3]}?']
    return ex('logic', 'comparisons', turns, ans, why, 'graph of the stated comparisons (sources/sinks)', rng)


def c_syllogism(rng):
    a, b, c, x = rng.choice([('dogs', 'mammals', 'animals', 'Rex'), ('roses', 'flowers', 'plants', 'this bloom'), ('squares', 'rectangles', 'shapes', 'this tile'),
                             ('violins', 'string instruments', 'instruments', 'this one'), ('sparrows', 'birds', 'animals', 'Pip')])
    form = rng.choice(['valid', 'undistributed', 'member', 'nonmember'])
    if form == 'valid':
        turns = [f'All {a} are {b}. All {b} are {c}. Are all {a} {c}?']
        return ex('logic', 'syllogism', turns, 'Yes', f'Every one of the {a} is among the {b}, and every one of those is among the {c}.', 'set inclusion', rng)
    if form == 'undistributed':
        turns = [f'All {a} are {c}. All {b} are {c}. Are all {b} {a}?']
        return ex('logic', 'syllogism', turns, 'Cannot be determined', f'Both groups are inside the {c}, but that says nothing about how the {a} and the {b} relate.',
                  'set inclusion (undistributed middle)', rng)
    if form == 'member':
        turns = [f'All {b} are {c}. {x[0].upper() + x[1:]} is one of the {b}. Is {x} one of the {c}?']
        return ex('logic', 'syllogism', turns, 'Yes', f'{x} is among the {b}, and all {b} are {c}.', 'set membership', rng)
    turns = [f'All {a} are {b}. {x[0].upper() + x[1:]} is not one of the {b}. Could {x} be one of the {a}?']
    return ex('logic', 'syllogism', turns, 'No', f'Every one of the {a} is among the {b}; {x} is not among the {b}, so it cannot be one of the {a}.', 'contrapositive', rng)


