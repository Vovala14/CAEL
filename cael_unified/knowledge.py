def edit_distance(left, right):
    previous = list(range(len(right) + 1))
    for i, a in enumerate(left, 1):
        current = [i]
        for j, b in enumerate(right, 1):
            current.append(min(current[-1] + 1, previous[j] + 1, previous[j - 1] + (a != b)))
        previous = current
    return previous[-1]


@lru_cache(maxsize=4)
def phrase_index(path, modified):
    """Source-title phrases only; never learn spellings from user conversations."""
    index = {}
    with closing(sqlite3.connect(Path(path).as_uri() + '?mode=ro', uri=True)) as connection:
        for alias, title in connection.execute('SELECT a.alias,d.title FROM aliases a JOIN documents d ON d.id=a.docid'):
            tokens = content_words(alias)
            for size in range(2, min(6, len(tokens)) + 1):
                phrase = tuple(tokens[-size:])
                for position, token in enumerate(phrase):
                    index.setdefault((size, position, token), set()).add((phrase, title))
    return index


def readable_excerpt(text):
    return (intact_text(text) and text.count('(') == text.count(')') and not re.search(r'(?i)\b(?:a|an|the|of|as|by|with|in|at|from|to|and|or|is|are|was|were)\s+[.,;:]', text)
            and not re.search(r'(?i)\b(?:respects|as follows|the following|namely)\s*[:.]?$', text))


def causal_evidence(text, terms):
    lower = text.lower()
    cues = list(re.finditer(r'\b(?:caused by|causes? of|result(?:s|ing)? from|because|due to|formed by|produced by|occurs? when|triggered by|generated by|driven by|major cause)\b', lower))
    anchors = [match for term in terms for match in re.finditer(r'\b' + re.escape(term.rstrip('s')) + r's?\b', lower)]
    return any(abs(cue.start() - anchor.start()) < 110 for cue in cues for anchor in anchors)


def matches_terms(terms, text):
    present = set(content_words(text))
    return all(any(form in present for form in (term, term + 's', term + 'r', term + 'er', term + 'est')) for term in terms)
SCHEMA = '''
CREATE TABLE IF NOT EXISTS documents(id INTEGER PRIMARY KEY, title TEXT, domain TEXT, revision INTEGER,
 revision_time TEXT, retrieved_at TEXT, url TEXT, article_url TEXT);
CREATE TABLE IF NOT EXISTS aliases(alias TEXT, docid INTEGER, UNIQUE(alias, docid));
CREATE INDEX IF NOT EXISTS aliases_key ON aliases(alias);
CREATE VIRTUAL TABLE IF NOT EXISTS passages USING fts5(title, heading, body, docid UNINDEXED, position UNINDEXED,
 tokenize='porter unicode61 remove_diacritics 2');
CREATE TABLE IF NOT EXISTS metadata(key TEXT PRIMARY KEY, value TEXT);
CREATE TABLE IF NOT EXISTS document_spans(docid INTEGER PRIMARY KEY, first_row INTEGER, last_row INTEGER);
'''


def add_document(connection, record):
    docid = int(record['pageid'])
    if connection.execute('SELECT 1 FROM documents WHERE id=?', (docid,)).fetchone():
        connection.execute('DELETE FROM passages WHERE docid=?', (docid,))
        connection.execute('DELETE FROM aliases WHERE docid=?', (docid,))
    connection.execute('INSERT OR REPLACE INTO documents VALUES(?,?,?,?,?,?,?,?)',
        (docid, record['title'], record.get('domain', 'Online reference'), record.get('revision'), record.get('revision_time'),
         record['retrieved_at'], record['url'], record.get('article_url', record['url'])))
    aliases = {record['title'], *record.get('aliases', [])}
    unqualified = re.sub(r'\s*\([^)]*\)$', '', record['title'])
    aliases.add(unqualified)
    for alias in aliases:
        connection.execute('INSERT OR IGNORE INTO aliases VALUES(?,?)', (normalize(alias), docid))
    position = 0
    first_row = last_row = None
    for section in record['sections']:
        for paragraph in section['paragraphs']:
            paragraph = re.sub(r'\s*\(\s*\)', '', paragraph)
            paragraph = re.sub(r'\(\s*;\s*', '(', paragraph)
            cursor = connection.execute('INSERT INTO passages VALUES(?,?,?,?,?)',
                (record['title'], section['heading'], paragraph, docid, position))
            first_row = cursor.lastrowid if first_row is None else first_row
            last_row = cursor.lastrowid
            position += 1
    connection.execute('INSERT OR REPLACE INTO document_spans VALUES(?,?,?)', (docid, first_row, last_row))


def answer_features(kind, heading, body, position, terms):
    text = body.lower()
    heading = heading.lower()
    terms = set(terms)
    features = {'bias': 1., 'intro': float(heading == 'introduction'), 'first': float(position == 0),
                'overlap': len(terms & set(words(body))) / max(1, len(terms)),
                'short': float(15 <= len(body.split()) <= 85)}
    cues = {'cause': ('cause', 'because', 'reason', 'due to', 'result from', 'resulting from', 'causation', 'origin'),
            'mechanism': ('mechanism', 'process', 'principle', 'operation', 'function', 'produced', 'converts', 'convert', 'works by', 'mechanics', 'drivetrain', 'working', 'power transmission'),
            'location': ('located', 'location', 'geography', 'found in', 'native to', 'situated', 'distribution', 'country in', 'city in', 'continent', 'lies in', 'border'),
            'time': ('history', 'invented', 'born', 'developed', 'first', 'origin', 'founded'),
            'definition': (' is ', ' are ', 'refers to', 'defined as', 'definition')}
    for name, values in cues.items():
        features['heading_' + name] = float(any(cue in heading for cue in values))
        features['body_' + name] = float(any(cue in text for cue in values))
    features['body_mechanism'] = float(any(cue in text for cue in ('converts', 'convert ', 'operates', 'operate ', 'works by',
        'driven by', 'rotates', 'powered by', 'produced by', 'transmits', 'transferred', 'uses a', 'uses the', 'through the interaction')))
    return {kind + ':' + key: value for key, value in features.items()}


class KnowledgeStore:
    def __init__(self, path=None, online_path=None, ranker_path=None):
        self.path = Path(path or DEFAULT)
        self.online_path = Path(online_path or ONLINE)
        self.ranker_path = Path(ranker_path or self.path.parent / 'ranker.json')
        self.ranker = json.loads(self.ranker_path.read_text(encoding='utf-8')) if self.ranker_path.exists() else {}
        self.local = threading.local()

    def connection(self, path):
        if not path.is_file():
            return None
        cache = getattr(self.local, 'connections', None)
        if cache is None:
            self.local.connections = cache = {}
        key = str(path.resolve())
        if key not in cache:
            connection = sqlite3.connect(path.resolve().as_uri() + '?mode=ro', uri=True, timeout=3)
            connection.row_factory = sqlite3.Row
            cache[key] = connection
        return cache[key]

    def document(self, subject, terms):
        matches = []
        for path in (self.online_path, self.path):
            connection = self.connection(path)
            if connection is None:
                continue
            exact = connection.execute('SELECT d.* FROM aliases a JOIN documents d ON d.id=a.docid WHERE a.alias=?',
                                       (normalize(subject),)).fetchall()
            # Expire downloaded-on-demand references independently of the frozen training snapshot.
            if path == self.online_path:
                exact = [row for row in exact if self.online_fresh(row)]
            if exact:
                matches.extend((connection, row, True) for row in exact)
        unique = {}
        for connection, row, exact in matches:
            unique.setdefault(row['title'], (connection, row, exact))
        if len(unique) == 1:
            return next(iter(unique.values()))
        if len(unique) > 1:
            return dict(ambiguous=sorted(unique)[:6])
        if not terms:
            return None
        # A near-title match needs complete subject coverage; a shared word is insufficient.
        query = ' OR '.join('"' + term.replace('"', '') + '"' for term in dict.fromkeys(terms))
        candidates = []
        for path in (self.online_path, self.path):
            connection = self.connection(path)
            if connection is None:
                continue
            rows = connection.execute('SELECT docid, title, body, bm25(passages,10,2,1) AS score FROM passages '
                                      'WHERE passages MATCH ? ORDER BY score LIMIT 24', (query,)).fetchall()
            for row in rows:
                title_terms = set(content_words(row['title']))
                wanted = set(terms)
                # Accept simple plural variants, never discard an unmatched named entity.
                stem = lambda w: w[:-1] if w.endswith('s') and len(w) > 3 and not w.endswith('ss') else w
                wanted_stems = {stem(w) for w in wanted}
                title_stems = {stem(w) for w in title_terms}
                if wanted_stems != title_stems and not (len(wanted_stems) >= 2 and wanted_stems <= title_stems):
                    # Descriptive questions may anchor a title ("why is the sky blue").
                    # Require every remaining content term in that candidate passage.
                    if not title_stems or not title_stems <= wanted_stems or not wanted_stems <= {stem(w) for w in content_words(row['body'])}:
                        continue
                document = connection.execute('SELECT * FROM documents WHERE id=?', (row['docid'],)).fetchone()
                if path == self.online_path and not self.online_fresh(document):
                    continue
                candidates.append((connection, document, False))
        unique = {}
        for connection, row, exact in candidates:
            unique.setdefault(row['title'], (connection, row, exact))
        if len(unique) > 1:
            anchored = {title: value for title, value in unique.items() if terms[0] in content_words(title)}
            if len(anchored) == 1:
                unique = anchored
        return next(iter(unique.values())) if len(unique) == 1 else dict(ambiguous=sorted(unique)[:6]) if unique else None

    def subject_suggestion(self, terms):
        if not 2 <= len(terms) <= 6 or not self.path.is_file():
            return None
        index = phrase_index(str(self.path.resolve()), self.path.stat().st_mtime_ns)
        options = set()
        for position, token in enumerate(terms):
            options.update(index.get((len(terms), position, token), ()))
        candidates = []
        for phrase, title in options:
            differences = [(a, b) for a, b in zip(terms, phrase) if a != b]
            if len(differences) != 1:
                continue
            left, right = differences[0]
            if len(left) < 4 or len(right) < 4 or left[0] != right[0]:
                continue
            distance = edit_distance(left, right)
            if distance <= 2:
                candidates.append((distance, ' '.join(phrase), title))
        if not candidates:
            return None
        best = min(item[0] for item in candidates)
        finalists = {(phrase, title) for distance, phrase, title in candidates if distance == best}
        return next(iter(finalists)) if len(finalists) == 1 else None

    @staticmethod
    def online_fresh(row):
        return (datetime.now(timezone.utc) - datetime.fromisoformat(row['retrieved_at'])).total_seconds() < 30 * 86400

    def document_rows(self, connection, docid):
        span = None
        if connection is self.connection(self.path):
            span = self.ranker.get('document_ranges', {}).get(str(docid))
        if span is None:
            try:
                span = connection.execute('SELECT first_row,last_row FROM document_spans WHERE docid=?', (docid,)).fetchone()
            except sqlite3.OperationalError:
                pass  # Older immutable snapshots use the checked sidecar or the slower fallback.
        if span and span[0] is not None:
            return connection.execute('SELECT heading,body,position FROM passages WHERE rowid BETWEEN ? AND ? ORDER BY rowid', tuple(span)).fetchall()
        return connection.execute('SELECT heading,body,position FROM passages WHERE docid=? ORDER BY CAST(position AS INTEGER)', (docid,)).fetchall()

    def lookup(self, parsed):
        if not parsed or not parsed['static']:
            return None
        if parsed['kind'] == 'comparison':
            return self.comparison(parsed)
        found = self.document(parsed['subject'], parsed['terms'])
        if found is None:
            suggestion = None if parsed.get('suggested') else self.subject_suggestion(parsed['terms'])
            if suggestion:
                phrase, title = suggestion
                answer = self.lookup(dict(parsed, subject=title, terms=content_words(title), suggested=True))
                if answer and answer['route'] == 'chat/local-knowledge':
                    answer['response'] = f'If you mean "{phrase}": ' + answer['response']
                    answer['details'] += f' Possible spelling correction: {parsed["subject"]!r} -> {phrase!r}; not assumed certain.'
                    answer['knowledge']['suggested_subject'] = phrase
                    return answer
                return dict(response=f'Did you mean "{phrase}"?', route='chat/local-knowledge-suggestion', sources=[],
                            details='A unique nearby source-title phrase was found; the intended subject needs confirmation.')
            return None
        if isinstance(found, dict):
            return dict(response='Which meaning do you mean: ' + '; '.join(found['ambiguous']) + '?',
                        route='chat/local-knowledge-ambiguous', sources=[], details='Multiple local article meanings; no meaning was guessed.')
        connection, document, exact = found
        if not intact_text(document['title']):
            return None
        passages = self.document_rows(connection, document['id'])
        # Never shorten away a lost character and then treat the remainder as
        # an intact quote. Definitions still require their original first intro.
        if parsed['kind'] != 'definition':
            passages = [row for row in passages if intact_text(row['body']) and intact_text(row['heading'])]
        extras = set(parsed['terms']) - set(content_words(document['title']))
        if extras and parsed['kind'] == 'definition':
            # "the rules of chess" is its own article ("Rules of chess"); a paragraph of
            # "Chess" that merely mentions rules (its history section) is not a definition.
            return None
        if extras:
            passages = [row for row in passages if extras <= set(content_words(row['body']))]
        if not passages:
            return None
        if parsed['kind'] == 'historical-event':
            from .news_time import historical_excerpt
            selected = historical_excerpt(passages, parsed, document['title'])
            if selected is None or not readable_excerpt(selected[0]):
                return None
            text, chosen = selected
            answer = self.answer(text, document, chosen, exact)
            answer['details'] += ' One explicitly dated source event; not a complete history of that year.'
            return answer
        if parsed['kind'] == 'time':
            selected = temporal_excerpt(passages, parsed, document['title'])
            minimum = 3 if parsed.get('event') in ('founded', 'formed', 'started') else 8
            if selected is None or not readable_excerpt(selected[0]) or len(selected[0].split()) < minimum:
                return None
            text, chosen = selected
            answer = self.answer(text, document, chosen, exact)
            if text not in chosen['body'] and text.startswith(document['title'] + ' '):
                answer['details'] += ' Source subject pronoun expanded to the article title; other wording retained.'
            return answer
        weights = self.ranker.get('answer_weights', {})
        kind = parsed['kind']
        if kind == 'definition':
            passages = [row for row in passages if row['heading'] == 'Introduction'] or passages[:1]
            passages = passages[:1]  # General definitions must start with the article's overview.
            if not intact_text(passages[0]['body']) or not intact_text(passages[0]['heading']):
                return None
        def rank(row):
            features = answer_features(kind, row['heading'], row['body'], int(row['position']), parsed['terms'])
            return sum(weights.get(key, 0.) * value for key, value in features.items()) - .001 * int(row['position'])
        ordered = sorted(passages, key=rank, reverse=True)
        if kind == 'cause':
            ordered = [row for row in ordered if causal_evidence(row['body'], parsed['terms'])]
            if not ordered:
                return None
            # Introductory explanations precede incidental causal mentions in later history.
            introductory = [row for row in ordered if row['heading'] == 'Introduction']
            if introductory:
                ordered = introductory + [row for row in ordered if row not in introductory]
        if kind in ('mechanism', 'location'):
            intro = passages[0]
            intro_features = answer_features(kind, intro['heading'], intro['body'], int(intro['position']), parsed['terms'])
            focused = []
            if kind == 'mechanism':
                focused = [row for row in ordered
                           if re.fullmatch(r'(?i)mechanisms?|process|principles?|operation|working principle|overview|how it works', row['heading'].strip())
                           and answer_features(kind, row['heading'], row['body'], int(row['position']), parsed['terms']).get('mechanism:body_mechanism')
                           and readable_excerpt(row['body'])]
            if focused:
                ordered = focused + [row for row in ordered if row not in focused]
            elif intro['heading'] == 'Introduction' and intro_features.get(kind + ':body_' + kind):
                ordered = [intro] + [row for row in ordered if row != intro]
        chosen = ordered[0]
        if kind == 'mechanism':
            evidenced = [row for row in ordered if answer_features(kind, row['heading'], row['body'], int(row['position']), parsed['terms']).get(kind + ':body_' + kind)]
            if not evidenced:
                return None
            chosen = evidenced[0]
        # Type evidence is required for non-definition questions. Never return an intro as a supposed cause/mechanism.
        features = answer_features(kind, chosen['heading'], chosen['body'], int(chosen['position']), parsed['terms'])
        if kind != 'definition' and not (features.get(kind + ':heading_' + kind) or features.get(kind + ':body_' + kind)):
            return None
        cleaned = re.sub(r'\s*\(\s*\)', '', chosen['body'])
        cleaned = re.sub(r'\(\s*;\s*', '(', cleaned)
        text = shorten(cleaned, words=65, sentences=2)
        if kind != 'definition':
            # Select an extractive sentence window containing type evidence rather than
            # truncating before the explanatory part of a long paragraph.
            parts = re.split(r'(?<=[.!?])\s+(?=[A-Z])', cleaned)
            windows = [' '.join(parts[i:i + 2]) for i in range(len(parts))]
            extras = set(parsed['terms']) - set(content_words(document['title']))
            if kind == 'cause' and extras:
                # Two source sentences from the same paragraph can retain both the
                # causal explanation and the requested property without an unrelated aside.
                causal = [part for part in parts if causal_evidence(part, parsed['terms'])]
                properties = [part for part in parts if matches_terms(extras, part)]
                windows += [left + ' ' + right for left in causal for right in properties if left != right]
            def window_rank(window):
                features = answer_features(kind, chosen['heading'], window, 0, parsed['terms'])
                evidence = features.get(kind + ':body_' + kind, 0)
                extras = set(parsed['terms']) - set(content_words(document['title']))
                coverage = float(matches_terms(extras, window)) if extras else 0.
                causal = 30 * int(causal_evidence(window, parsed['terms'])) if kind == 'cause' else 0
                overlap = float(matches_terms(parsed['terms'], window)) if extras else features.get(kind + ':overlap', 0)
                locations = [cleaned.find(part) for part in parts if part in window]
                span = max(locations) - min(locations) if locations else 0
                return causal + coverage * 20 + evidence * 10 + overlap - span * .001 + sum(weights.get(k, 0.) * v for k, v in features.items()) * .01
            text = shorten(max(windows, key=window_rank), words=75 if kind == 'cause' else 65, sentences=2)
            final_features = answer_features(kind, chosen['heading'], text, 0, parsed['terms'])
            if not (final_features.get(kind + ':heading_' + kind) or final_features.get(kind + ':body_' + kind)):
                return None
            if extras and not matches_terms(extras, text):
                return None
            if kind == 'cause' and not causal_evidence(text, parsed['terms']):
                return None
        if not readable_excerpt(text):
            return None
        if len(text.split()) < 8:
            return None
        return self.answer(text, document, chosen, exact)

    @staticmethod
    def answer(text, document, chosen, exact):
        attribution = 'Wikipedia contributors; extracted from the local snapshot and shortened by CAEL'
        return dict(response=text, route='chat/local-knowledge', sources=[dict(source='Wikipedia — ' + document['title'],
                    title=document['title'], url=document['url'], licence='CC BY-SA 4.0', licence_url=CCBYSA, attribution=attribution)],
                    details=f"Local reference: {document['title']} / {chosen['heading']}. Retrieved {document['retrieved_at']}; revision {document['revision']}. "
                            f"Snapshot excerpt, not a fresh verification. {attribution}. CC BY-SA 4.0: {CCBYSA}",
                    knowledge=dict(title=document['title'], heading=chosen['heading'], internet_used=False, exact_subject=exact))

    def comparison(self, parsed):
        text = parsed['original'].strip(' ?.!,')
        patterns = [r'compare (.+?) (?:and|with) (.+)', r'(?:what is the )?difference between (.+?) and (.+)',
                    r'how do (.+?) and (.+?) differ', r'what distinguishes (.+?) from (.+)', r'(.+?) versus (.+)']
        match = next((match for pattern in patterns if (match := re.fullmatch(pattern, text, re.I))), None)
        if not match:
            return None
        left, right = match.groups()
        found = [self.document(subject, content_words(subject)) for subject in (left, right)]
        if any(value is None or isinstance(value, dict) for value in found):
            return None
        terms = set(content_words(left) + content_words(right))
        candidates = []
        for connection, document, _ in found:
            rows = self.document_rows(connection, document['id'])
            for row in rows:
                if not intact_text(row['body']) or not intact_text(row['heading']) or not intact_text(document['title']):
                    continue
                if not terms <= set(content_words(row['body'])):
                    continue
                sentences = re.split(r'(?<=[.!?])\s+(?=[A-Z])', row['body'])
                for index in range(len(sentences)):
                    window = ' '.join(sentences[index:index + 2])
                    if terms <= set(content_words(window)) and re.search(r'(?i)\b(?:unlike|whereas|differ\w*|in contrast|compared with|compared to|instead of)\b', window):
                        excerpt = shorten(window, words=70, sentences=2)
                        if not excerpt.endswith('…') and excerpt.endswith(('.', '!', '?')) and readable_excerpt(excerpt):
                            candidates.append((len(excerpt.split()), excerpt, document, row['heading']))
        if not candidates:
            return None
        _, excerpt, document, heading = min(candidates, key=lambda row: row[0])
        attribution = 'Wikipedia contributors; contrast passage selected from the local snapshot by CAEL'
        return dict(response=excerpt, route='chat/local-knowledge-comparison', sources=[dict(source='Wikipedia — ' + document['title'],
                    title=document['title'], url=document['url'], licence='CC BY-SA 4.0', licence_url=CCBYSA, attribution=attribution)],
                    details=f"Local reference: {document['title']} / {heading}; revision {document['revision']}. "
                            f"Retrieved {document['retrieved_at']}. {attribution}. CC BY-SA 4.0: {CCBYSA}",
                    knowledge=dict(title=document['title'], heading=heading, internet_used=False))

    def remember(self, record):
        """Persist only canonical public provider text, never prompts or conversations."""
        if record.get('licence') != 'CC BY-SA 4.0' or not record.get('revision') or not record['url'].startswith('https://en.wikipedia.org/'):
            return False
        if not intact_text(record.get('title')) or any(not intact_text(section['heading']) or any(not intact_text(body) for body in section['paragraphs']) for section in record['sections']):
            return False  # Preserve an existing clean public-cache entry.
        self.online_path.parent.mkdir(parents=True, exist_ok=True)
        with closing(sqlite3.connect(self.online_path, timeout=10)) as connection, connection:
            connection.execute('PRAGMA journal_mode=WAL')
            connection.executescript(SCHEMA)
            add_document(connection, record)
            excess = connection.execute('SELECT id FROM documents ORDER BY retrieved_at DESC LIMIT -1 OFFSET 5000').fetchall()
            for (docid,) in excess:
                connection.execute('DELETE FROM passages WHERE docid=?', (docid,))
                connection.execute('DELETE FROM aliases WHERE docid=?', (docid,))
                connection.execute('DELETE FROM documents WHERE id=?', (docid,))
        return True
