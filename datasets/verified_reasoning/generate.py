def d_sources(rng):
    kind = rng.choice(['no_priority', 'priority', 'correction', 'withdrawn', 'hearsay', 'newest'])
    label = rng.choice(['Report', 'Log', 'Witness', 'Note', 'Sheet'])
    L1, L2 = rng.sample(['A', 'B', 'C', 'North', 'South', 'Red', 'Blue', '1', '2'], 2)
    topic, vals = rng.choice([('the gate opened at', ['08:12', '08:20', '08:21', '07:55']), ('the meeting is in room', ['Elm', 'Ash', 'Oak', 'Birch']),
                              ('the delivery came at', ['10:00', '14:00', '11:30', '16:15']), ('the visitor count was', ['120', '125', '118', '131']),
                              ('the bell rang', ['once', 'twice', 'three times'])])
    v1, v2, v3 = rng.sample(vals, 3) if len(vals) >= 3 else (vals[0], vals[1], vals[0])
    s1, s2 = f'{label} {L1}', f'{label} {L2}'
    base = f'{s1} says {topic} {v1}. {s2} says {topic} {v2}.'
    if kind == 'no_priority':
        turns = [base + ' Neither source is more reliable than the other. What do these sources establish?']
        return ex('conflicting_sources', kind, turns, 'Cannot be determined', f'The two sources disagree ({v1} vs {v2}) and neither has priority, so the answer stays open.',
                  'rule-based resolution', rng)
    if kind == 'priority':
        win = rng.choice([s1, s2])
        turns = [f'When the sources disagree, trust {win}.', base + ' What should we record?']
        return ex('conflicting_sources', kind, turns, v1 if win == s1 else v2, f'By the stated rule {win} wins, so the value is {v1 if win == s1 else v2}.', 'rule-based resolution', rng)
    if kind == 'correction':
        to = v2 if rng.random() < 0.5 else v3
        turns = [base, f'{s1} has now corrected its entry to {to}. Do the sources agree now?']
        same = to == v2
        return ex('conflicting_sources', kind, turns, f'Yes, {to}' if same else 'No',
                  f'After the correction {s1} says {to} and {s2} says {v2}; ' + ('they agree.' if same else 'they still disagree.'), 'rule-based resolution', rng)
    if kind == 'withdrawn':
        gone = rng.choice([s1, s2])
        stay, sv = (s2, v2) if gone == s1 else (s1, v1)
        turns = [base, f'{gone} has withdrawn its statement. Which source still has a claim on record, and what does it say?']
        return ex('conflicting_sources', kind, turns, f'{stay}: {topic} {sv}', f'{gone} withdrew, so only {stay} remains: {topic} {sv}.', 'rule-based resolution', rng)
    if kind == 'hearsay':
        n_first = rng.randint(1, 3)
        n_copy = rng.randint(1, 2)
        names = rng.sample(NAMES, n_first + n_copy)
        lines = [f'{nm} saw it personally and says {topic} {rng.choice(vals)}.' for nm in names[:n_first]]
        lines += [f'{nm} only heard it from {rng.choice(names[:n_first])}.' for nm in names[n_first:]]
        rng.shuffle(lines)
        turns = [' '.join(lines) + ' How many first-hand accounts are there?']
        return ex('conflicting_sources', kind, turns, str(n_first), f'{n_first} {"person" if n_first == 1 else "people"} saw it themselves; the other {n_copy} only repeat{"s" if n_copy == 1 else ""} someone else.', 'counting by provenance', rng)
    y1 = rng.randint(2015, 2021)
    y2 = y1 + rng.randint(1, 3)
    order = rng.random() < 0.5
    turns = [(f'The leaflet printed in {y1} says {topic} {v1}. The website updated in {y2} says {topic} {v2}.' if order else
              f'The website updated in {y2} says {topic} {v2}. The leaflet printed in {y1} says {topic} {v1}.') + ' Which is the current information?']
    return ex('conflicting_sources', kind, turns, v2, f'The website ({y2}) is newer than the leaflet ({y1}), so its value {v2} is current.', 'recency rule', rng)


