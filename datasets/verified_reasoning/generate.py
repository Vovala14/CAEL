def key_of(row):
    text = ' || '.join(m['content'] for m in row['messages']).lower()
    return hashlib.sha256(text.encode()).hexdigest()


def build(n, seed, exclude=frozenset(), keep=None, quota=None, attempts=8):
    """Generate up to n unique rows. `keep` filters rows (for the hard set); `quota` caps rows per category."""
    weights = [w for _, w in MIX]
    rows, seen, stats = [], set(exclude), Counter()
    per_cat = Counter()
    master = random.Random(seed)
    i = 0
    while len(rows) < n and i < n * attempts:
        i += 1
        gen = master.choices([g for g, _ in MIX], weights=weights)[0]
        rng = random.Random(f'{seed}:{i}')
        try:
            row = gen(rng)
        except (ValueError, IndexError, ZeroDivisionError):
            row = None
        if row is None:
            stats['rejected'] += 1
            continue
        k = key_of(row)                                  # duplicates are judged on the problem itself, before rewording
        if k in seen:
            stats['duplicates'] += 1
            continue
        row['difficulty'] = difficulty(row)
        if keep and not keep(row):
            continue
        if quota and per_cat[row['category']] >= quota.get(row['category'], 0):
            continue
        seen.add(k)
        vary(row, rng)
        row['grids'] = json.dumps(row['grids']) if 'grids' in row else ''
        row.setdefault('rule', '')
        row['key'] = k
        rows.append(row)
        per_cat[row['category']] += 1
    return rows, stats


COLUMNS = ['id', 'category', 'task', 'difficulty', 'messages', 'answer', 'solution', 'verification', 'grids', 'rule', 'generator']


def write(rows, out, name, per=250000):
    import pyarrow as pa
    import pyarrow.parquet as pq
    parts = max(1, math.ceil(len(rows) / per))
    for p in range(parts):
        chunk = rows[p * per:(p + 1) * per]
        table = pa.Table.from_pylist([{c: r[c] for c in COLUMNS} for r in chunk])
        pq.write_table(table, out / f'{name}-{p:05d}-of-{parts:05d}.parquet', compression='zstd', row_group_size=8192)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='data')
    ap.add_argument('--n', type=int, default=2000000, help='rows in train + test')
    ap.add_argument('--hard', type=int, default=1500, help='rows in the separate hard evaluation set')
    ap.add_argument('--seed', type=int, default=2026)
    ap.add_argument('--test-share', type=float, default=0.01)
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    rows, stats = build(args.n, args.seed)
    split = random.Random(args.seed + 1)
    test_ids = set(split.sample(range(len(rows)), int(len(rows) * args.test_share)))
    train, test = [], []
    for j, r in enumerate(rows):
        r['id'] = f'cvr-{j:07d}'
        (test if j in test_ids else train).append(r)
    # the hard set: a different seed, only difficulty >= 3, balanced by category, never a problem that is in train or test
    cats = sorted({r['category'] for r in rows})
    quota = {c: math.ceil(args.hard / len(cats)) for c in cats}
    hard, _ = build(args.hard, args.seed + 7919, exclude=frozenset(r['key'] for r in rows), keep=lambda r: r['difficulty'] >= 3,
                    quota=quota, attempts=400)
    for j, r in enumerate(hard):
        r['id'] = f'cvr-hard-{j:05d}'
    write(train, out, 'train')
    write(test, out, 'test')
    write(hard, out, 'hard')
    summary = dict(version=VERSION, seed=args.seed, train=len(train), test=len(test), hard=len(hard),
                   by_category=dict(Counter(r['category'] for r in rows).most_common()),
                   hard_by_category=dict(Counter(r['category'] for r in hard).most_common()),
                   difficulty=dict(sorted(Counter(r['difficulty'] for r in rows).items())),
                   duplicates_skipped=stats['duplicates'], by_task=dict(Counter(r['task'] for r in rows).most_common()))
    (out / 'stats.json').write_text(json.dumps(summary, indent=1), encoding='utf-8')
    print(json.dumps({k: v for k, v in summary.items() if k != 'by_task'}, indent=1))


if __name__ == '__main__':
    main()
